"""Resolve defects.yaml anchors to file:line and write organizer/ANSWER_KEY.md.

Fails loudly if an anchor no longer matches, so the key never drifts from the code.

  python organizer/build_answer_key.py
"""
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def locate(file, pattern):
    lines = (ROOT / file).read_text(encoding="utf-8").splitlines()
    rx = re.compile(pattern)
    for n, line in enumerate(lines, 1):
        if rx.search(line):
            return n, line.strip()
    return None, None


def render(items, missing):
    out = []
    for d in items:
        out.append(f"### {d['id']} - {d['title']}\n")
        for file, pattern in d["anchors"]:
            n, line = locate(file, pattern)
            if n is None:
                missing.append(f"{d['id']}: {file} /{pattern}/")
                continue
            out.append(f"- `{file}:{n}` - `{line[:110]}`")
        if d.get("observe"):
            out.append(f"\n**Teams observe:** {d['observe']}  ")
            out.append(f"**Expected fix:** {d['fix']}  ")
            out.append(f"**Hits:** {', '.join(d['hits'])}")
        out.append("")
    return out


def main():
    spec = yaml.safe_load((HERE / "defects.yaml").read_text(encoding="utf-8"))
    missing = []
    lines = [
        "# TicketPilot ANSWER KEY (organizers only - never commit)",
        "",
        f"{len(spec['defects'])} catalog defects + {len(spec['bonus'])} bonus findings. "
        "Generated by `python organizer/build_answer_key.py` from `organizer/defects.yaml`.",
        "",
        "Scoring: 1 point per 3 catalog IDs correctly named in a team write-up (cap 10). "
        "Bonus findings are not in the catalog; judges may credit them under Engineering quality.",
        "",
        "## Catalog defects",
        "",
    ]
    lines += render(spec["defects"], missing)
    lines += ["## Bonus findings (not scored as catalog IDs)", ""]
    lines += render(spec["bonus"], missing)
    (HERE / "ANSWER_KEY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if missing:
        print("Unresolved anchors:\n  " + "\n  ".join(missing))
        sys.exit(1)
    print(f"Wrote {HERE / 'ANSWER_KEY.md'}")


if __name__ == "__main__":
    main()
